package generate

import (
	"cuelang.org/go/cue/ast"
	"cuelang.org/go/cue/format"
	"cuelang.org/go/cue/token"
)

func id(s string) ast.Expr  { return ast.NewIdent(s) }
func str(s string) ast.Expr { return ast.NewString(s) }
func union(xs ...ast.Expr) ast.Expr {
	if len(xs) == 0 {
		return &ast.BottomLit{}
	}
	if len(xs) == 1 {
		return xs[0]
	}
	return ast.NewBinExpr(token.OR, xs...)
}
func and(xs ...ast.Expr) ast.Expr { return ast.NewBinExpr(token.AND, xs...) }
func field(s string, v ast.Expr, optional bool) *ast.Field {
	f := &ast.Field{Label: ast.NewString(s), Value: v}
	if optional {
		f.Constraint = token.OPTION
	} else {
		f.Constraint = token.NOT
	}
	return f
}
func def(s string, v ast.Expr) *ast.Field { return &ast.Field{Label: ast.NewIdent("#" + s), Value: v} }
func obj(fs ...*ast.Field) *ast.StructLit {
	s := &ast.StructLit{}
	for _, f := range fs {
		s.Elts = append(s.Elts, f)
	}
	return s
}
func list(v ast.Expr) ast.Expr      { return ast.NewList(&ast.Ellipsis{Type: v}) }
func tuple(vs ...ast.Expr) ast.Expr { return ast.NewList(vs...) }
func pattern(label, value ast.Expr) *ast.StructLit {
	return &ast.StructLit{Elts: []ast.Decl{&ast.Field{Label: ast.NewList(label), Value: value}}}
}
func sel(pkg, name string) ast.Expr { return ast.NewSel(ast.NewIdent(pkg), "#"+name) }
func file(pkg string) *ast.File {
	return &ast.File{Decls: []ast.Decl{&ast.Package{Name: ast.NewIdent(pkg)}}}
}
func addImport(f *ast.File, alias, path string) {
	d := &ast.ImportDecl{Specs: []*ast.ImportSpec{ast.NewImport(ast.NewIdent(alias), path)}}
	i := 0
	for i < len(f.Decls) {
		switch f.Decls[i].(type) {
		case *ast.Package, *ast.ImportDecl:
			i++
		default:
			goto insert
		}
	}
insert:
	f.Decls = append(f.Decls, nil)
	copy(f.Decls[i+1:], f.Decls[i:])
	f.Decls[i] = d
}
func render(f *ast.File) ([]byte, error) {
	b, e := format.Node(f, format.Simplify())
	if e != nil {
		return nil, e
	}
	return append([]byte("// Code generated by cfn-cue. DO NOT EDIT.\n\n"), b...), nil
}
